# Generates src/core/width.zig: East Asian Wide/Fullwidth ranges (2 cells) and
# zero-width ranges (0 cells), from Python's unicodedata. Rerun from the repo
# root after a Unicode update: python tools/gen-width.py
import unicodedata

def ranges(pred, limit=0x110000):
    out = []
    start = None
    for cp in range(limit):
        if 0xD800 <= cp <= 0xDFFF:
            v = False
        else:
            try:
                ch = chr(cp)
            except ValueError:
                v = False
            else:
                v = pred(ch, cp)
        if v and start is None:
            start = cp
        elif not v and start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, limit - 1))
    return out

wide = ranges(lambda ch, cp: unicodedata.east_asian_width(ch) in ('W', 'F'))
zero = ranges(lambda ch, cp: unicodedata.category(ch) in ('Mn', 'Me', 'Cf'))

with open('src/core/width.zig', 'w', encoding='utf-8', newline='\n') as f:
    f.write('//! Generated by tools/gen-width.py from unicodedata %s.\n' % unicodedata.unidata_version)
    f.write('//! East Asian Wide/Fullwidth ranges (2 cells) and zero-width ranges (0 cells).\n')
    f.write('//! Do not edit by hand; rerun the script after a Unicode update.\n\n')
    f.write('pub const Range = struct { lo: u21, hi: u21 };\n\n')
    f.write('pub const wide = [_]Range{\n')
    for lo, hi in wide:
        f.write('    .{ .lo = 0x%X, .hi = 0x%X },\n' % (lo, hi))
    f.write('};\n\n')
    f.write('pub const zero = [_]Range{\n')
    for lo, hi in zero:
        f.write('    .{ .lo = 0x%X, .hi = 0x%X },\n' % (lo, hi))
    f.write('};\n\n')
    f.write('''fn inRanges(rs: []const Range, cp: u21) bool {
    var lo: usize = 0;
    var hi: usize = rs.len;
    while (lo < hi) {
        const mid = lo + (hi - lo) / 2;
        if (rs[mid].hi < cp) {
            lo = mid + 1;
        } else {
            hi = mid;
        }
    }
    return lo < rs.len and rs[lo].lo <= cp and cp <= rs[lo].hi;
}

/// Display width in cells: 0 (combining/format), 1, or 2 (wide/fullwidth).
pub fn cellWidth(cp: u21) u8 {
    if (inRanges(&zero, cp)) return 0;
    if (inRanges(&wide, cp)) return 2;
    return 1;
}
''')

print('wrote src/core/width.zig: %d wide ranges, %d zero-width ranges' % (len(wide), len(zero)))
